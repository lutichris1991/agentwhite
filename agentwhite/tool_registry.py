def _installed(tool: dict[str, Any]) -> tuple[bool, list[str]]:
    evidence: list[str] = []
    executables = tool.get("executables") or []
    modules = tool.get("python_modules") or []

    for executable in executables:
        path = shutil.which(str(executable))
        if path:
            evidence.append(path)

    for module in modules:
        try:
            found = importlib.util.find_spec(str(module)) is not None
        except (ImportError, ValueError):
            found = False
        if found:
            evidence.append(f"python:{module}")

    # Registry-only frameworks may intentionally have no single executable.
    if not executables and not modules:
        return False, evidence
    return bool(evidence), evidence


def list_tools() -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for item in TOOL_CATALOG:
        installed, evidence = _installed(item)
        row = dict(item)
        row["installed"] = installed
        row["detected"] = evidence
        row["policy"] = dict(POLICY_DEFAULTS)
        rows.append(row)
    return rows


def get_tool(tool_id: str) -> dict[str, Any] | None:
    for item in list_tools():
        if item["id"] == tool_id:
            return item
    return None
